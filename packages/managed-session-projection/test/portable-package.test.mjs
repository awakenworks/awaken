const manifest = { name: '@awaken/managed-session-projection', version: '0.1.2', description: 'Projection', license: 'Apache-2.0' };
const fixtures = {
  runtime: 'export { MANAGED_SESSION_EVENT_TYPES } from "@awaken/managed-sdk-oracle/current-wire";',
  declarations: 'import type { BetaManagedAgentsSession, BetaManagedAgentsSessionEvent, BetaManagedAgentsStreamSessionEvents } from "@awaken/managed-sdk-oracle/current-types";\nexport { MANAGED_SESSION_EVENT_TYPES } from "@awaken/managed-sdk-oracle/current-wire";\nexport type Event = BetaManagedAgentsSessionEvent;',
  wireRuntime: 'export const MANAGED_SESSION_EVENT_TYPES = ["user.tool_confirmation"];',
  wireDeclarations: 'export declare const MANAGED_SESSION_EVENT_TYPES: readonly ["user.tool_confirmation"];',
};
const digest = 'a'.repeat(64);

test('portable package gzip has one platform marker without changing its payload, checksum or input bytes', () => {
  const content = Buffer.from('canonical package contents\n'), linux = gzipSync(content), windows = Buffer.from(linux);
  linux[9] = 3; windows[9] = 10;
  const canonical = canonicalPackageBytes(linux);
  assert.deepEqual(canonicalPackageBytes(windows), canonical); assert.deepEqual(gunzipSync(canonical), content);
  assert.deepEqual(canonical.subarray(10), linux.subarray(10)); assert.equal(canonical[9], 255);
  assert.equal(linux[9], 3); assert.equal(windows[9], 10);
  const headerCrc = Buffer.from(linux); headerCrc[3] = 2;
  assert.throws(() => canonicalPackageBytes(headerCrc), /Unexpected package gzip header/);
  assert.throws(() => canonicalPackageBytes(Buffer.alloc(17)), /Unexpected package gzip header/);
});

test('portable output normalizes compiler newlines without changing literal escapes or generated provenance', () => {
  const files = {...fixtures, runtime: fixtures.runtime + '\nexport const literal = "\\r\\n";\n',
    wireRuntime: '// GENERATED by @awaken/managed-sdk-oracle; do not edit.\n' + fixtures.wireRuntime + '\n'};
  const crlf = Object.fromEntries(Object.entries(files).map(([name, value]) => [name, value.replaceAll('\n', '\r\n')]));
  const expected = portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', files, digest);
  assert.deepEqual(portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', crlf, digest), expected);
  assert.match(expected['dist/index.js'], /literal = "\\r\\n"/);
  assert.match(expected['dist/current-wire.js'], /GENERATED by @awaken\/managed-sdk-oracle/);
});

test('source provenance normalizes UTF-8 newlines and preserves file boundaries', () => {
  const lf = [Buffer.from('原文\nkept\n'), Buffer.from('{"compiler":"pinned"}\n')];
  const crlf = lf.map(value => Buffer.from(value.toString('utf8').replaceAll('\n', '\r\n')));
  assert.equal(sourceInputsSha256(lf), sourceInputsSha256(crlf));
  assert.notEqual(sourceInputsSha256(lf), sourceInputsSha256([lf[0], Buffer.from('{"compiler":"changed"}\n')]));
  assert.notEqual(sourceInputsSha256([Buffer.from('ab'), Buffer.from('c')]), sourceInputsSha256([Buffer.from('a'), Buffer.from('bc')]));
});

test('pack output and cleanup refuse checkout or foreign directories', () => {
  const repository = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
  assert.throws(() => packPortable(repository, { build: false }), /outside the checkout/);
  const foreign = mkdtempSync(join(tmpdir(), 'foreign-projection-consumer-'));
  const sentinel = join(foreign, 'retained');
  writeFileSync(sentinel, 'owned by another operation');
  try {
    assert.throws(() => removeOwnedTemporary(foreign, 'awaken-projection-consumer-'), /Refusing cleanup/);
    assert.equal(existsSync(sentinel), true);
  } finally { removeOwnedTemporary(foreign, 'foreign-projection-consumer-'); }
});

test('portable distribution retains the selected SDK and canonical generated catalog without workspace runtime dependencies', () => {
  const files = portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', fixtures, digest);
  const pkg = JSON.parse(files['package.json']);
  assert.deepEqual(pkg.dependencies, { '@anthropic-ai/sdk': '0.132.1' });
  assert.equal(pkg.private, true); assert.equal(Object.hasOwn(pkg, 'scripts'), false);
  assert.equal(files['dist/current-wire.js'], fixtures.wireRuntime); assert.equal(files['dist/current-wire.d.ts'], fixtures.wireDeclarations);
  assert.match(files['dist/index.js'], /\.\/current-wire\.js/); assert.doesNotMatch(files['dist/index.js'], /oracle/);
  assert.match(files['dist/index.d.ts'], /@anthropic-ai\/sdk\/resources\/beta\/sessions\/sessions/);
  assert.match(files['dist/index.d.ts'], /@anthropic-ai\/sdk\/resources\/beta\/sessions\/events/);
  assert.equal(JSON.parse(files['dist/provenance.json']).sourceInputsSha256, digest);
});

test('portable distribution refuses unknown canonical type imports, unpinned SDKs and private runtime references', () => {
  for (const sdk of ['workspace:*', '^0.132.1', 'npm:@anthropic-ai/sdk@latest']) assert.throws(() => portableArtifacts(manifest, sdk, fixtures, digest), /Exact selected SDK/);
  assert.throws(() => portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', fixtures, 'bad'), /source digest/);
  assert.throws(() => portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', { ...fixtures, declarations: fixtures.declarations.replace('BetaManagedAgentsSession,', 'UnknownSdkType,') }, digest), /Unmapped/);
  assert.throws(() => portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', { ...fixtures, runtime: 'import "@awaken/managed-sdk-oracle/other";' }, digest), /Non-portable/);
  for (const runtime of ['import("@awaken/managed-sdk-oracle/private");', 'import "../sibling/index.js";', 'import "node:fs";', 'import(dynamicName);']) assert.throws(() => portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', { ...fixtures, runtime }, digest), /Non-portable/);
  assert.throws(() => portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', { ...fixtures, declarations: fixtures.declarations + '\nexport type Hidden = import("@awaken/managed-sdk-oracle/private").Hidden;' }, digest), /Non-portable/);
  const documented = portableArtifacts(manifest, 'npm:@anthropic-ai/sdk@0.132.1', { ...fixtures, wireRuntime: '// GENERATED by @awaken/managed-sdk-oracle; do not edit.\n' + fixtures.wireRuntime }, digest);
  assert.match(documented['dist/current-wire.js'], /GENERATED by @awaken\/managed-sdk-oracle/);
});

test('packed projection runs and typechecks from an isolated external consumer with no sibling checkout', () => {
  const owned = mkdtempSync(join(tmpdir(), 'awaken-projection-consumer-'));
  try {
    const tarball = packPortable(owned, { build: false });
    const consumer = join(owned, 'consumer');
    mkdirSync(consumer);
    writeFileSync(join(consumer, 'package.json'), JSON.stringify({ private: true, type: 'module',
      dependencies: { '@awaken/managed-session-projection': 'file:../' + tarball.slice(dirname(tarball).length + 1) },
      devDependencies: { typescript: '5.9.3', '@types/node': '26.1.0' } }));
    packageManager(['install', '--prefer-offline', '--ignore-scripts', '--no-frozen-lockfile'], consumer);
    const modules = resolve(consumer, 'node_modules');
    assert(modules.startsWith(resolve(owned) + sep));
    rmSync(modules, { recursive: true, force: true });
    packageManager(['install', '--offline', '--ignore-scripts', '--frozen-lockfile'], consumer);
    const installed = realpathSync(join(consumer, 'node_modules/@awaken/managed-session-projection'));
    assert(installed.startsWith(resolve(consumer) + sep), 'production package must not resolve to the sibling source checkout');
    const installedManifest = JSON.parse(readFileSync(join(installed, 'package.json'), 'utf8'));
    assert.equal(installedManifest.version, '0.1.2');
    assert.deepEqual(installedManifest.dependencies, { '@anthropic-ai/sdk': '0.132.1' });
    const runtime = `
      import assert from 'node:assert/strict';
      import {createRequire} from 'node:module';
      import {mergeCommittedEvents, projectManagedSessionRuntime, managedSessionAdmission, pairToolResults, ManagedProjectionConflictError} from '@awaken/managed-session-projection';
      const call={id:'call',type:'agent.custom_tool_use',name:'propose_command',input:{command:'example'},processed_at:null};
      const idle={id:'idle',type:'session.status_idle',stop_reason:{type:'requires_action',event_ids:['call']},processed_at:'2026-11-09T00:00:00Z'};
      const pending=projectManagedSessionRuntime([call,idle]);assert(pending.pendingToolIds.has('call'));assert(managedSessionAdmission(pending,'idle').canResolveTools);
      const reply={id:'reply',type:'user.custom_tool_result',custom_tool_use_id:'call',content:[{type:'text',text:'original reply'}],is_error:false,processed_at:null};
      const accepted=[call,idle,reply],resolving=projectManagedSessionRuntime(accepted);assert(resolving.resolvingToolIds.has('call'));assert.equal(managedSessionAdmission(resolving,'idle').canResolveTools,false);assert.equal(managedSessionAdmission(resolving,'idle').canSendMessage,false);
      const enriched=mergeCommittedEvents(accepted,[{...reply,processed_at:'2026-11-09T00:00:01Z'}]);assert.equal(projectManagedSessionRuntime(enriched).resolvingToolIds.size,0);assert.equal(pairToolResults(enriched).get('call').id,'reply');
      assert.throws(()=>mergeCommittedEvents(enriched,[{...call,input:{command:'changed'}}]),ManagedProjectionConflictError);
      assert.throws(()=>createRequire(import.meta.url).resolve('@awaken/managed-sdk-oracle/current-wire'),{code:'MODULE_NOT_FOUND'});
    `;
    writeFileSync(join(consumer, 'consumer.mjs'), runtime);
    const execution = spawnSync(process.execPath, ['consumer.mjs'], { cwd: consumer, encoding: 'utf8' });
    assert.equal(execution.status, 0, execution.stdout + execution.stderr);
    writeFileSync(join(consumer, 'consumer.ts'), `
      import { projectManagedSessionRuntime, managedSessionAdmission, type ManagedEvent } from '@awaken/managed-session-projection';
      const call: ManagedEvent = {id:'call',type:'agent.custom_tool_use',name:'propose_command',input:{command:'example'},processed_at:null};
      const projection=projectManagedSessionRuntime([call]);
      managedSessionAdmission(projection,'idle');
      // @ts-expect-error only official aggregate statuses are accepted
      managedSessionAdmission(projection,'invented-state');
    `);
    writeFileSync(join(consumer, 'tsconfig.json'), JSON.stringify({ compilerOptions: { target: 'ES2023', module: 'NodeNext', moduleResolution: 'NodeNext', strict: true, noEmit: true, skipLibCheck: false, types: ['node'] }, include: ['consumer.ts'] }));
    packageManager(['exec', 'tsc', '-p', 'tsconfig.json'], consumer);
  } finally { removeOwnedTemporary(owned, 'awaken-projection-consumer-'); }
});
